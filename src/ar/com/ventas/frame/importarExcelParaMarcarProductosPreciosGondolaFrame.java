    private void marcar() {
        if(productosGondola != null && !productosGondola.isEmpty()){
            for (Producto pr : productosGondola) {
                String detalle = pr.getDetalle();
                try {
                    Producto np = new ProductoService().getByDescripcion(detalle);
                    np.setActualizarGondola(true);
                    np.setListaPdf(true);
                    new ProductoService().updateProducto(np);
                } catch (Exception ex) {
//                    Logger.getLogger(importarExcelParaMarcarProductosPreciosGondolaFrame.class.getName()).log(Level.SEVERE, null, ex);
//                    continue;
                }
            }
        }
    }

