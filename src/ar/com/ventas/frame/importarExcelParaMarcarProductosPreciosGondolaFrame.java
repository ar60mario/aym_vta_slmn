    private void llenarTablaProductosImportados() throws IOException, BiffException, Exception {
        productosGondola = LectorDeExcel.leerExcelProductosParaPreciosGondola(archivoImportado);
        DefaultTableModel modelo = (DefaultTableModel) tabla.getModel();
        if (productosGondola != null && !productosGondola.isEmpty()) {
            for (Producto pr : productosGondola) {
                Object[] fila = new Object[1];
                fila[0] = pr.getDetalle();
                modelo.addRow(fila);
            }
            tabla.setModel(modelo);
        } else {
            Object[] mensaje = new Object[1];
            mensaje[0] = "No se recuperó ningún PRODUCTO del archivo";
            modelo.addRow(mensaje);
//            aceptarBtn.setEnabled(false);
        }
    }

